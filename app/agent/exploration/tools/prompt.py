def _yaml_metadata_block(value: dict[str, int]) -> str:
    body = yaml.safe_dump(value, allow_unicode=True, sort_keys=False).rstrip('\n')
    fence = '`' * max(3, 1 + max((len(run) for run in re.findall(r'`+', body)), default=0))
    return f'{fence}yaml\n{body}\n{fence}'


def build_exploration_supplemental(
    user: AuthenticatedUser,
    *,
    extra: str = '',
) -> str:
    """构造探索任务单轮附加上下文（`### 平台访问等级`），传入 `TreeAgent.generate(..., supplemental=...)`。"""
    validated = AuthenticatedUser.model_validate(user.model_dump())
    sections: list[str] = []
    if extra and extra.strip():
        sections.append(extra.strip())
    if validated.platform_permissions:
        sorted_permissions = dict(sorted(validated.platform_permissions.items()))
        sections.append('### 平台访问等级\n\n' + _yaml_metadata_block(sorted_permissions))
    else:
        sections.append('### 平台访问等级\n\n当前用户未配置任何平台文件访问等级。')
    return '\n\n'.join(sections)


